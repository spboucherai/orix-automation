cd "$(dirname "$0")/.."
MISSING=0
while IFS= read -r -d '' f; do
  if ! head -12 "$f" | grep -q "Author: Simon-Pierre Boucher"; then echo "missing header: $f"; MISSING=1; fi
done < <(git ls-files -z -- '*.swift' '*.sh' '*.py' 'project.yml')
