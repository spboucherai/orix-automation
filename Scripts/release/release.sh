# ORIX OS Automation
# File: Scripts/release/release.sh
# Description: Full release: tests, Release build, secret scan, signature check, notarize the app, build and notarize the DMG, checksums, Gatekeeper verdict, evidence in docs/release/.
#
# Author: Simon-Pierre Boucher
# Contact: contact@spboucher.ai
#   Scripts/release/release.sh [--skip-tests]
# Uses the EXISTING notary keychain profile (NOTARY_PROFILE, default MacLustr-Notarize). Creates no credential.
set -euo pipefail
cd "$(dirname "$0")/../.."
APP="dist/ORIX OS Automation.app"
if [[ "${1:-}" != "--skip-tests" ]]; then Scripts/test/test-all.sh; fi
Scripts/check-headers.sh
Scripts/build/build.sh release
[[ -d "$APP" ]] || { echo "ERROR: release build did not produce $APP" >&2; exit 1; }
VERSION="$(/usr/libexec/PlistBuddy -c 'Print CFBundleShortVersionString' "$APP/Contents/Info.plist")"
BUILD="$(/usr/libexec/PlistBuddy -c 'Print CFBundleVersion' "$APP/Contents/Info.plist")"
Scripts/release/secret-scan.sh "$APP" | tee build/secret-scan.txt
Scripts/release/sign.sh
Scripts/release/notarize.sh "$APP" app
Scripts/release/package.sh all
DMG="dist/ORIX-OS-Automation-$VERSION.dmg"
Scripts/release/notarize.sh "$DMG" dmg
Scripts/release/package.sh checksums
echo "== Gatekeeper"
spctl --assess --type execute -vv "$APP" 2>&1 | tee build/spctl-app.txt
spctl --assess --type open --context context:primary-signature -vv "$DMG" 2>&1 | tee build/spctl-dmg.txt
EVIDENCE="docs/release/release-$VERSION-$BUILD.md"
{
  echo "<!--"; echo "ORIX OS Automation"; echo "File: $EVIDENCE"; echo "Author: Simon-Pierre Boucher"; echo "Contact: contact@spboucher.ai"; echo "-->"
  echo "# Release evidence — $VERSION ($BUILD)"; echo
  echo "Generated by \`Scripts/release/release.sh\` on $(date -u +%Y-%m-%dT%H:%M:%SZ). Nothing below is typed by hand."; echo
  echo "## Secret scan"; echo '```'; cat build/secret-scan.txt; echo '```'
  echo "## Signature"; echo '```'; codesign -dvv "$APP" 2>&1 | grep -E "^(Identifier|Authority|TeamIdentifier|Timestamp|Runtime|Format|CodeDirectory)" ; echo '```'
  echo "## Architectures"; echo '```'; lipo -archs "$APP/Contents/MacOS/ORIX OS Automation"; echo '```'
  echo "## Entitlements"; echo '```'; codesign -d --entitlements - --xml "$APP" 2>/dev/null | plutil -p - 2>/dev/null || echo "none"; echo '```'
  echo "## Notarization"; echo '```'
  for n in app dmg; do /usr/bin/python3 -c 'import json,sys; d=json.load(open(sys.argv[1])); print(sys.argv[2], d.get("id"), d.get("status"))' "build/notary/$n.json" "$n"; done
  echo '```'
  echo "## Staple"; echo '```'; xcrun stapler validate "$APP" 2>&1 | tail -1; xcrun stapler validate "$DMG" 2>&1 | tail -1; echo '```'
  echo "## Gatekeeper"; echo '```'; cat build/spctl-app.txt build/spctl-dmg.txt; echo '```'
  echo "## Checksums (SHA-256)"; echo '```'; cat dist/SHA256SUMS.txt; echo '```'
} > "$EVIDENCE"
echo "evidence: $EVIDENCE"
